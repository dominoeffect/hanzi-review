def clean(units):
    total = 0
    seen = set()
    for u in units:
        for les in u["lessons"]:
            for c in les["chars"]:
                total += 1
                if c["char"] in seen:
                    print("DUP", c["char"])
                seen.add(c["char"])
                if "similar" in c:
                    sims = []
                    for s in c["similar"]:
                        if s != c["char"] and s not in sims:
                            sims.append(s)
                    c["similar"] = sims[:3]
                    if not c["similar"]:
                        del c["similar"]
    print("TOTAL", total, "UNIQUE", len(seen))
    return total

